import { test } from '@e2e-dev/mobile';
import { localSyntheticEnabled } from './local-mode';
import { reveal } from './reveal';
import { expect } from 'e2e';
import { syntheticBoardId, syntheticRows } from './synthetic-store';

test('board edit, archive, restore and delete persist across relaunch', { skip: !localSyntheticEnabled, tags: ['deterministic', 'boards'], timeout: 180_000 }, async ({ app, screen, device }) => {
  const original = `QA Manage ${Date.now()}`;
  const renamed = `${original} edited`;
  await app.open();
  await screen.getByTestId('create-board').tap();
  await screen.getByTestId('board-form-save').tap();
  await reveal(screen, screen.getByTestId('board-form-error'));
  await expect(screen.getByTestId('board-form-error')).toBeVisible();
  await reveal(screen, screen.getByTestId('board-title-input'), { direction: 'up' });
  await screen.getByTestId('board-title-input').fill(original);
  await device.dismissKeyboard();
  await screen.getByTestId('board-form-save').tap();
  await reveal(screen, screen.getByRole('button', { name: original }));
  await expect(screen.getByRole('button', { name: original })).toBeVisible();
  const id = syntheticBoardId(original);
  await screen.getByRole('button', { name: original }).tap();
  await screen.getByTestId('edit-board').tap();
  await screen.getByTestId('board-title-input').fill(renamed);
  await device.dismissKeyboard();
  await screen.getByTestId('board-form-save').tap();
  await app.restart();
  await expect(screen.getByRole('button', { name: renamed })).toBeVisible();
  await expect(screen.getByRole('button', { name: original })).not.toBeVisible();
  await reveal(screen, screen.getByRole('button', { name: renamed }));
  await screen.getByRole('button', { name: renamed }).tap();
  await screen.getByTestId('edit-board').tap();
  await reveal(screen, screen.getByTestId('archive-board'));
  await screen.getByTestId('archive-board').tap();
  await screen.getByRole('button', { name: 'Archive', exact: true }).tap();
  await expect.poll(() => syntheticRows(`select id from boards where id='${id}' and archived_at is not null and deleted_at is null`).length).toBe(1);
  await app.restart();
  await expect(screen.getByRole('button', { name: renamed })).not.toBeVisible();
  await screen.getByTestId('open-settings').tap();
  await reveal(screen, screen.getByTestId('open-archived-boards'));
  await screen.getByTestId('open-archived-boards').tap();
  await screen.getByRole('button', { name: `${renamed}, archived board` }).tap();
  await screen.getByTestId('restore-board').tap();
  await expect.poll(() => syntheticRows(`select id from boards where id='${id}' and archived_at is null and deleted_at is null`).length).toBe(1);
  await app.restart();
  await reveal(screen, screen.getByRole('button', { name: renamed }));
  await screen.getByRole('button', { name: renamed }).tap();
  await screen.getByTestId('edit-board').tap();
  await reveal(screen, screen.getByTestId('form-delete-board'));
  await screen.getByTestId('form-delete-board').tap();
  await screen.getByRole('button', { name: 'Delete Board', exact: true }).last().tap();
  await expect.poll(() => syntheticRows(`select id from boards where id='${id}' and deleted_at is not null`).length).toBe(1);
  await app.restart();
  await expect(screen.getByRole('button', { name: renamed })).not.toBeVisible();
});
