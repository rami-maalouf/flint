import { replaceField } from "./replace-field";
import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { reveal } from './reveal';

test('board icon search, custom color, day shift and metrics preferences persist', { tags: ['deterministic', 'boards'], timeout: 240_000 }, async ({ app, screen, device }) => {
  const title = `QA Options ${Date.now()}`;
  await app.open();
  await expect(screen.getByTestId('create-board')).toBeVisible();
  await screen.getByTestId('create-board').tap();
  await expect(screen.getByTestId('board-title-input')).toBeVisible();
  await replaceField(screen.getByTestId('board-title-input'), title, { device, screen });
  await device.dismissKeyboard();
  await screen.getByTestId('open-symbol-picker').tap();
  await expect(screen.getByTestId('symbol-search')).toBeVisible();
  await replaceField(screen.getByTestId('symbol-search'), 'coffee', { device, screen });
  await expect(screen.getByTestId('symbol-cup.and.saucer.fill')).toBeVisible();
  await screen.getByTestId('symbol-cup.and.saucer.fill').tap();
  await expect(screen.getByTestId('board-title-input')).toBeVisible();
  await screen.getByTestId('custom-color').tap();
  await expect(screen.getByTestId('custom-color-input')).toBeVisible();
  await replaceField(screen.getByTestId('custom-color-input'), '#123456', { device, screen });
  await device.dismissKeyboard();
  await screen.getByTestId('tinted-toggle').tap();
  const tinted = await screen.getByTestId('tinted-toggle').isChecked();
  await reveal(device, screen, screen.getByTestId('open-options'));
  await screen.getByTestId('open-options').tap();
  await expect(screen.getByTestId('start-of-day-value')).toBeVisible();
  await screen.getByTestId('shift-later').tap();
  const shifted = await screen.getByTestId('start-of-day-value').textContent();
  await reveal(device, screen, screen.getByTestId('metrics-toggle'));
  await expect(screen.getByTestId('metrics-toggle')).toBeChecked();
  await screen.getByTestId('metrics-toggle').tap();
  await screen.getByTestId('options-back').tap();
  await expect(screen.getByTestId('board-form-save')).toBeVisible();
  await screen.getByTestId('board-form-save').tap();
  await reveal(device, screen, screen.getByRole('button', { name: title, exact: true }));
  await app.restart();
  await expect(screen.getByTestId('create-board')).toBeVisible({ timeout: 60_000 });
  await reveal(device, screen, screen.getByRole('button', { name: title, exact: true }));
  await screen.getByRole('button', { name: title, exact: true }).tap();
  await expect(screen.getByTestId('metrics-disabled')).toBeVisible();
  await screen.getByTestId('edit-board').tap();
  await expect(screen.getByTestId('board-title-input')).toBeVisible();
  if (tinted) await expect(screen.getByTestId('tinted-toggle')).toBeChecked();
  else await expect(screen.getByTestId('tinted-toggle')).not.toBeChecked();
  await screen.getByTestId('custom-color').tap();
  await expect(screen.getByTestId('custom-color-input')).toHaveValue('#123456');
  await screen.getByTestId('open-symbol-picker').tap();
  await expect(screen.getByTestId('symbol-search')).toBeVisible();
  await replaceField(screen.getByTestId('symbol-search'), 'coffee', { device, screen });
  await expect(screen.getByTestId('symbol-cup.and.saucer.fill')).toBeSelected();
  await screen.getByTestId('close-symbol-picker').tap();
  await reveal(device, screen, screen.getByTestId('open-options'));
  await screen.getByTestId('open-options').tap();
  await expect(screen.getByTestId('start-of-day-value')).toHaveText(shifted ?? '');
  await expect(screen.getByTestId('metrics-toggle')).not.toBeChecked();
});
